-- V1 基线迁移
--
-- 项目当前没有任何 JPA 实体或表定义，因此本迁移不包含 DDL。
-- 它的作用是建立 Flyway 的 schema history 基线，让后续结构变更从 V2 开始有序追加，
-- 同时为迁移目录提供一份可提交的占位文件。
--
-- 约定：
--   * 文件名使用 V<版本>__<描述>.sql，例如 V2__create_image_table.sql
--   * 已执行过的迁移不得修改，只能新增后续版本
--   * 破坏性变更（删列、改类型、回填）必须同时给出回滚或恢复方案
--   * 应用启动时 Flyway 会自动执行未应用的迁移；生产发布前先审查将要执行的脚本
--
-- 添加第一个实体时，用 ./mvnw 生成对应的 V2 迁移，不要在 ddl-auto 上放松为 update。
