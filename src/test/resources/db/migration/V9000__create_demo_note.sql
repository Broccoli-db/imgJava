-- 演示切片的建表脚本。
--
-- 为什么放在 src/test/resources/db/migration/ 而不是单独的目录：
--   DemoNote 是测试源码里的 JPA 实体，会被 Hibernate 的实体扫描全局捕获，
--   因此每一个 @SpringBootTest 上下文都会校验它的表是否存在。把它放进默认的
--   迁移位置（Flyway 会跨 classpath 合并 classpath:db/migration），所有测试都自动
--   拿到这张表，不需要每个测试类各自声明 flyway locations。
--   生产打包时测试资源不参与，所以这张表不会进生产迁移历史。
--
-- 为什么版本号是 9000：
--   让测试专用迁移永久规避与真实迁移的版本号冲突。将来生产加了 V2、V3……
--   也不会撞车（Flyway 允许版本号不连续）。
CREATE TABLE demo_note (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title   VARCHAR(200) NOT NULL,
    content TEXT         NOT NULL
);
